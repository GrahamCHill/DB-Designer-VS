const parse = (sql: string, dialect?: NonNullable<Parameters<typeof parseSql>[1]>['dialect']) =>
  parseSql([{ name: 'x.sql', content: sql }], { dialect }).schema;

/** A comparable summary: tables → columns(type, nullability, pk, unique) and FKs by name. */
function summary(s: Schema) {
  const byId = new Map(s.tables.map((t) => [t.id, t]));
  const tables = s.tables
    .map((t) => ({
      name: `${t.schema}.${t.name}`,
      cols: t.columns.map((c) => `${c.name}:${c.type}:${c.nullable && !c.pk ? 'null' : 'notnull'}:${c.pk ? 'pk' : ''}:${c.unique ? 'u' : ''}:${c.default ?? ''}`),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
  const fks = s.relations
    .map((r) => {
      const f = byId.get(r.fromTable)!;
      const t = byId.get(r.toTable)!;
      const fc = r.fromColumns.map((id) => f.columns.find((c) => c.id === id)!.name);
      const tc = r.toColumns.map((id) => t.columns.find((c) => c.id === id)!.name);
      return `${f.schema}.${f.name}(${fc}) -> ${t.schema}.${t.name}(${tc}) ${r.onDelete ?? ''} ${r.onUpdate ?? ''}`;
    })
    .sort();
  return { tables, fks };
}

test('full export round-trips through the parser', () => {
  const src = parse(`
    CREATE TABLE public.users (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), "Email" text UNIQUE NOT NULL, "order" int);
    CREATE TABLE app.posts (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE, body text);
    COMMENT ON TABLE app.posts IS 'It''s posts';
  `);
  const sql = generateFullSql(src);
  assert.match(sql, /CREATE SCHEMA IF NOT EXISTS app;/);
  assert.match(sql, /"Email" text NOT NULL/);
  assert.match(sql, /"order" int,/);
  assert.match(sql, /GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(sql, /COMMENT ON TABLE app\.posts IS 'It''s posts';/);
  const again = parseSql([{ name: 'out.sql', content: sql }]).schema;
  const a = summary(src);
  const b = summary(again);
  assert.deepEqual(b, a);
});

test('MSSQL types are converted to PostgreSQL', () => {
  assert.equal(toPostgresType('nvarchar(max)', 'mssql'), 'text');
  assert.equal(toPostgresType('nvarchar(200)', 'mssql'), 'varchar(200)');
  assert.equal(toPostgresType('uniqueidentifier', 'mssql'), 'uuid');
  assert.equal(toPostgresType('bit', 'mssql'), 'boolean');
  assert.equal(toPostgresType('datetime2', 'mssql'), 'timestamp');
  assert.equal(toPostgresType('tinyint(1)', 'mysql'), 'boolean');
  assert.equal(toPostgresType('int unsigned', 'mysql'), 'bigint');
  const s = parse(
    `CREATE TABLE [dbo].[T] ([Id] INT IDENTITY(1,1) PRIMARY KEY, [On] BIT NOT NULL DEFAULT ((0)), [At] DATETIME DEFAULT (getdate()))
     GO`,
    'mssql',
  );
  const sql = generateFullSql(s);
  assert.match(sql, /CREATE TABLE public\."T"/);
  assert.match(sql, /"Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
  assert.match(sql, /"On" boolean NOT NULL DEFAULT false/);
  assert.match(sql, /"At" timestamp DEFAULT now\(\)/);
});

test('diff: no edits produces no statements', () => {
  const s = parse(`CREATE TABLE a (id int PRIMARY KEY);`);
  assert.match(generateDiffSql(s, cloneSchema(s)), /No changes/);
});

test('diff: add/rename/alter/drop columns, tables, FKs', () => {
  const base = parse(`
    CREATE TABLE app.users (id uuid PRIMARY KEY, name text, legacy int, email text);
    CREATE TABLE app.posts (id int PRIMARY KEY, user_id uuid REFERENCES app.users(id));
    CREATE TABLE app.old (id int PRIMARY KEY);
  `);
  const cur = cloneSchema(base);
  const users = cur.tables.find((t) => t.name === 'users')!;
  users.name = 'accounts';
  users.columns.find((c) => c.name === 'name')!.name = 'full_name';
  users.columns.find((c) => c.name === 'full_name')!.nullable = false;
  users.columns.find((c) => c.name === 'email')!.unique = true;
  users.columns.find((c) => c.name === 'email')!.type = 'varchar(320)';
  users.columns = users.columns.filter((c) => c.name !== 'legacy');
  users.columns.push({ id: 'new1', name: 'created_at', type: 'timestamptz', nullable: false, pk: false, unique: false, default: 'now()' });
  cur.tables = cur.tables.filter((t) => t.name !== 'old');
  cur.tables.push({
    id: 'tnew',
    schema: 'app',
    name: 'comments',
    columns: [
      { id: 'cn1', name: 'id', type: 'bigint', nullable: false, pk: true, unique: false, identity: true },
      { id: 'cn2', name: 'post_id', type: 'integer', nullable: false, pk: false, unique: false },
    ],
  });
  const posts = cur.tables.find((t) => t.name === 'posts')!;
  cur.relations.push({ id: 'rnew', fromTable: 'tnew', fromColumns: ['cn2'], toTable: posts.id, toColumns: [posts.columns[0].id], onDelete: 'CASCADE' });
  cur.relations[0].onDelete = 'SET NULL';

  const sql = generateDiffSql(base, cur);
  const expect = [
    'ALTER TABLE app.posts DROP CONSTRAINT IF EXISTS posts_user_id_fkey;',
    'DROP TABLE IF EXISTS app.old;',
    'CREATE TABLE app.comments (',
    'ALTER TABLE app.users RENAME TO accounts;',
    'ALTER TABLE app.accounts DROP COLUMN IF EXISTS legacy;',
    'ALTER TABLE app.accounts RENAME COLUMN name TO full_name;',
    'ALTER TABLE app.accounts ALTER COLUMN full_name SET NOT NULL;',
    'ALTER TABLE app.accounts ALTER COLUMN email TYPE varchar(320) USING email::varchar(320);',
    'ALTER TABLE app.accounts ADD CONSTRAINT accounts_email_key UNIQUE (email);',
    'ALTER TABLE app.accounts ADD COLUMN created_at timestamptz NOT NULL DEFAULT now();',
    'ALTER TABLE app.posts ADD CONSTRAINT posts_user_id_fkey FOREIGN KEY (user_id) REFERENCES app.accounts (id) ON DELETE SET NULL;',
    'ALTER TABLE app.comments ADD CONSTRAINT comments_post_id_fkey FOREIGN KEY (post_id) REFERENCES app.posts (id) ON DELETE CASCADE;',
  ];
  let at = -1;
  for (const line of expect) {
    const i = sql.indexOf(line);
    assert.ok(i >= 0, `missing: ${line}\n---\n${sql}`);
    assert.ok(i > at, `out of order: ${line}\n---\n${sql}`);
    at = i;
  }
  assert.match(sql, /^BEGIN;$/m);
  assert.match(sql, /^COMMIT;$/m);
});

const SAMPLE = path.resolve(__dirname, '..', '../MPUDOH-ContractManagementTool/db');
test('sample round-trip: Contract Management schema', { skip: !fs.existsSync(SAMPLE) && 'sample folder not present' }, () => {
  const files = fs
    .readdirSync(SAMPLE)
    .filter((f) => f.endsWith('.sql'))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .map((f) => ({ name: f, content: fs.readFileSync(path.join(SAMPLE, f), 'utf8') }));
  const src = parseSql(files).schema;
  const again = parseSql([{ name: 'out.sql', content: generateFullSql(src) }]).schema;
  assert.deepEqual(summary(again), summary(src));
});
