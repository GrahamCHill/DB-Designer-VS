import { test } from 'node:test';
import * as assert from 'node:assert/strict';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import type { SqlJsStatic } from 'sql.js';
import { buildSchema } from '../src/introspect/index';
import { introspectSqlite } from '../src/introspect/sqlite';
import { generateFullSql } from '../src/shared/pgExport';

// eslint-disable-next-line @typescript-eslint/no-var-requires
const initSqlJs: () => Promise<SqlJsStatic> = require('sql.js/dist/sql-asm.js');

test('SQLite introspection: columns, PKs, uniques, FKs (incl. implicit PK target)', async () => {
  const SQL = await initSqlJs();
  const db = new SQL.Database();
  db.run(`
    PRAGMA foreign_keys = ON;
    CREATE TABLE artist (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE, born DATETIME DEFAULT CURRENT_TIMESTAMP);
    CREATE TABLE album (id INTEGER PRIMARY KEY, artist_id INTEGER NOT NULL REFERENCES artist ON DELETE CASCADE, title TEXT);
    CREATE TABLE track (album_id INTEGER, no INTEGER, title TEXT, PRIMARY KEY (album_id, no), FOREIGN KEY (album_id) REFERENCES album(id));
  `);
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'erd-')), 'music.db');
  fs.writeFileSync(file, Buffer.from(db.export()));
  db.close();

  const s = buildSchema('sqlite', await introspectSqlite(file));
  const t = (n: string) => s.tables.find((x) => x.name === n)!;
  assert.deepEqual(s.tables.map((x) => x.name).sort(), ['album', 'artist', 'track']);
  assert.equal(t('artist').columns[0].identity, true);
  assert.equal(t('artist').columns.find((c) => c.name === 'name')!.unique, true);
  assert.deepEqual(t('track').columns.filter((c) => c.pk).map((c) => c.name), ['album_id', 'no']);
  assert.equal(s.relations.length, 2);
  const albumFk = s.relations.find((r) => r.fromTable === t('album').id)!;
  assert.equal(albumFk.toTable, t('artist').id);
  assert.equal(albumFk.onDelete, 'CASCADE');

  const sql = generateFullSql(s);
  assert.match(sql, /CREATE TABLE public\.artist \(\n {4}id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
  assert.match(sql, /born timestamp DEFAULT CURRENT_TIMESTAMP/);
  assert.match(sql, /FOREIGN KEY \(artist_id\) REFERENCES public\.artist \(id\) ON DELETE CASCADE/);
});
